function getCategoryMeta(rawCategory) {
  return CATEGORY_MAP[rawCategory] || null;
}

function categorySeoName(rawCategory) {
  const meta = getCategoryMeta(rawCategory);
  return (meta && meta.seoName) || (rawCategory ? `${rawCategory} с логотипом` : '');
}

